// Today's entry, or the nearest one in the coming two weeks.
export function todayInHistory(now = new Date()) {
  const fmt = (d: Date) =>
    new Intl.DateTimeFormat('en-GB', { timeZone: 'Asia/Jerusalem', day: '2-digit', month: '2-digit' }).format(d);
  for (let i = 0; i < 14; i++) {
    const d = new Date(now.getTime() + i * 86400000);
    const hits = onThisDay.filter((e) => e.date === fmt(d));
    if (hits.length) return { ...hits[0], today: i === 0 };
  }
  return undefined;
}
